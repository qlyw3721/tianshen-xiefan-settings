def rep(old, new, tag):
    global t
    c = t.count(old)
    assert c == 1, 'REP[%s] 命中 %d 次' % (tag, c)
    t = t.replace(old, new, 1)
    log.append('REP ' + tag)


def line_find(prefix, tag):
    return _find(prefix, tag)


def _find(prefix, tag):
    lines = t.split(NL)
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, 'LINE[%s] 命中 %d 次' % (tag, len(idx))
    return idx[0]


def replace_line(prefix, txt, tag):
    global t
    lines = t.split(NL)
    lines[_find(prefix, tag)] = txt
    t = NL.join(lines)
    log.append('LINE ' + tag)


def insert_before(prefix, block, tag):
    global t
    lines = t.split(NL)
    i = _find(prefix, tag)
    lines[i:i] = block.split(NL)
    t = NL.join(lines)
    log.append('INS ' + tag)


def insert_after(prefix, block, tag):
    global t
    lines = t.split(NL)
    i = _find(prefix, tag)
    lines[i + 1:i + 1] = block.split(NL)
    t = NL.join(lines)
    log.append('INS-AFTER ' + tag)


