def rep_span(n, start, end, new, tag=''):
    s = L[n - 1]
    assert s.count(start) == 1, ('START', n, tag, s.count(start))
    assert s.count(end) == 1, ('END', n, tag, s.count(end))
    i, j = s.find(start), s.find(end)
    assert 0 <= i < j, ('ORDER', n, tag, i, j)
    L[n - 1] = s[:i] + new + s[j + len(end):]
    print('OK span', n, tag)


def rep(n, old, new, tag=''):
    s = L[n - 1]
    assert s.count(old) == 1, ('REP', n, tag, s.count(old))
    L[n - 1] = s.replace(old, new, 1)
    print('OK rep ', n, tag)


