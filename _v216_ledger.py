# -*- coding: utf-8 -*-
"""v2.16 台账更新（纯 LF）"""
import io

P = "设定集_裁定台账.md"
t = io.open(P, encoding="utf-8", newline="").read()
assert "\r\n" not in t, "台账应为纯 LF"

def rep(old, new, tag):
    global t
    n = t.count(old)
    assert n == 1, "[%s] 期望 1 处，实际 %d 处" % (tag, n)
    t = t.replace(old, new, 1)
    print("  OK  " + tag)

# 1. A 区新增改判行（插在命名纪律行之后）
old = "| **原创命名风格纪律**（采纳·新建 §0.6 第三十三款） |"
i = t.index(old)
j = t.index("\n", i) + 1
row = ("| **兵甲轴级名改判「通造／具名／孤品」**（采纳·覆盖 v2.13 三名） | 用户令：「换成『通造／具名／孤品』，同时同步表、分篇、xmind 三处」。"
       "2 级 制式→**通造**（Common-forged）／3 级 名器→**具名**（Named）／5 级 秘藏→**孤品**（Unique）。"
       "**位次、举证、七位含义、级名不互称铁律、三处同步规则一律未动**，纯换用字；旧名废止。"
       "普通名词「制式」（制式法器／族徽制式／骑士团制式）与「秘藏」（世间秘藏）一处未动 | 2026-11-19 |\n")
t = t[:j] + row + t[j:]
print("  OK  A 区新增改判行")

# 2. 当前版本 → v2.16，v2.15 降为上一版
old = "| **当前版本** | 本机 **v2.15**（第五十四轮·"
i = t.index(old)
j = t.index("\n", i) + 1
v215_row = t[i:j]
v216_row = ("| **当前版本** | 本机 **v2.16**（第五十五轮·**兵甲轴三条级名改判**：制式→**通造**／名器→**具名**／秘藏→**孤品**，"
            "用户令「同时同步表、分篇、xmind 三处」；位次·举证·七位含义·级名不互称铁律全未动，纯换用字，旧名废止；"
            "§0.6 第三十二款八改写＋第三十三款抽检表三项核销、§10.5 章题·总表·两分篇·铁律·纪律、§10.1 银枪白莲、§10.4 紫曜弓、§11.1 登记；"
            "`物品等级体系.xmind` 8 处替换、121 节点不变）；md 12,941 行／2,507,905 B，docx 1,393,250 B／586 标题／566 表；在线仍 v1.93/version 32（未上传） | 2026-11-19 |\n")
t = t[:i] + v216_row + v215_row.replace("| **当前版本** |", "| **上一版** |", 1) + t[j:]
print("  OK  当前版本→v2.16")

# 3. 待裁挂起项核销
old = ("- **兵甲轴三条级名待裁（v2.15）**：2 级「制式」／3 级「名器」／5 级「秘藏」经命名风格抽检判为中式语汇，"
       "主推改「**通造／具名／孤品**」（备选 2 级「匠造」）。**位次、举证、三处同步一律不动**；裁前一切引用照旧，不得擅自改字。\n")
rep(old, "", "待裁挂起项核销")

assert "\r\n" not in t
io.open(P, "w", encoding="utf-8", newline="").write(t)
print("\n台账行数：%d" % (t.count("\n") + 1))
