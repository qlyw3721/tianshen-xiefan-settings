# -*- coding: utf-8 -*-
"""v2.21 台账：A 区定稿行 / 版本行 / 待裁核销 / 纠错档案"""
import io

P = "设定集_裁定台账.md"
t = io.open(P, encoding="utf-8", newline="").read()
assert "\r\n" not in t, "台账应为纯 LF"
L = t.split("\n")


def find_one(pred, tag):
    idx = [i for i, ln in enumerate(L) if pred(ln)]
    assert len(idx) == 1, "[%s] 命中 %d 处" % (tag, len(idx))
    return idx[0]


# 1. A 区新增（接 v2.20 梯度表行之后）
i = find_one(lambda ln: ln.startswith("| **可召上限逐阶梯度表**（采纳·§5.2 v2.20 补记立主表）"), "A区锚")
row = ("| **四推定格按推导定稿**（用户裁定·覆盖 v2.20 之【推定】标注） | "
       "用户令：「**原文无出处就按你的推导来**」。§5.2 梯度表中无原文直证的**四格**由【推定】升 **【定稿·v2.21】**："
       "**低阶 A 5 级／中阶 A 6 级／高阶 A 7 级／高阶 B 7 级**。**数字、位次、三条纪律一律未动，只改标注**。"
       "同时立一条纪律：**「定稿」＝本设定集采此数，非原文直证**——引用须说明是推导，不得标作原文；日后若出现新原文，以原文为准、本表退让。"
       "有原文锚的三格（L2805／L4068／§8.0 表 10 级）与半锚一格（L1889）标注未动。"
       "导图 5 处文本同步（125 节点不变） | 2026-11-20 |")
L.insert(i + 1, row)

# 2. 版本行
cur = find_one(lambda ln: ln.startswith("| **当前版本** | 本机 **v2.20**"), "当前版本")
old = L[cur]
new = ("| **当前版本** | 本机 **v2.21**（第六十轮·**四推定格定稿**：用户令「原文无出处就按你的推导来」；"
       "§5.2 梯度表四格【推定】→**【定稿·v2.21】**（低阶 A5／中阶 A6／高阶 A7／高阶 B7），数字位次纪律一格未动；"
       "新立纪律「**定稿＝本设定集采此数，非原文直证**」，引用不得标作原文；三锚格与半锚格标注未动；"
       "顺修 v2.20 戳「大魔法师 A9／B9」笔误为 **8–9 级**；"
       "md 13,152 行／2,550,383 B，docx 1,417,578 B／591 标题／578 表；`生物等级体系.xmind` 125 节点（不变）；"
       "在线仍 v2.20/version 34（本轮未明示同步，未上传） | 2026-11-20 |")
L[cur] = new
L.insert(cur + 1, old.replace("| **当前版本** |", "| **上一版** |", 1))

# 3. 待裁区核销
k = find_one(lambda ln: ln.startswith("- **可召上限表的 4 个推定格（v2.20）**"), "待裁锚")
L[k] = ("- ~~可召上限表的 4 个推定格（v2.20）：低阶 A5／中阶 A6／高阶 A7／高阶 B7~~ → "
        "**v2.21 用户裁定「原文无出处就按你的推导来」**，四格按推导定稿（§5.2 v2.20 补记）。"
        "**此条已核销，不再挂起**；以后若要动，仍只改主表一格，两处指针自动跟随。")

# 4. 纠错档案新增
last = max(i for i, ln in enumerate(L) if ln.startswith("| 以「有无战力」当唯一判据（v2.13）"))
L.insert(last + 1,
         "| 摘要戳与表内数字不符（v2.20） | 顶部 v2.20 戳写「大魔法师 10–16 → **A 9 级／B 9 级**」 | "
         "表内与同戳他处均为 **8–9 级** | **A9／B9 从未被采纳过，属笔误非决策**。教训："
         "**摘要戳不是正文，却是最先被读到的地方**——它一旦与表不符，读者会先信戳、后疑表；"
         "升版时戳与表须对读一遍，v2.21 已改为 8–9 级 |")

out = "\n".join(L)
io.open(P, "w", encoding="utf-8", newline="").write(out)
print("台账已更新，行数", out.count("\n") + 1)
for kw in ("四推定格按推导定稿", "本机 **v2.21**", "此条已核销", "摘要戳与表内数字不符"):
    print(kw, "->", out.count(kw))
