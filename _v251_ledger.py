# -*- coding: utf-8 -*-
"""v2.51 台账更新：版本四行滚动 + 纠错档案一条"""
P = '设定集_裁定台账.md'
s = open(P, 'rb').read().decode('utf-8')
assert '\r\n' not in s
L = s.split('\n')

def find(prefix):
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    assert len(idx) == 1, (prefix, idx)
    return idx[0]

i_cur = find('| **当前版本** | 本机 **v2.50**')
i_prev = find('| **上一版** | 本机 **v2.49**')
i_prev2 = find('| **上上版** | 本机 **v2.48**')
assert i_cur + 1 == i_prev and i_prev + 1 == i_prev2, (i_cur, i_prev, i_prev2)

L[i_cur] = L[i_cur].replace('| **当前版本** |', '| **上一版** |', 1)
L[i_prev] = L[i_prev].replace('| **上一版** |', '| **上上版** |', 1)
L[i_prev2] = L[i_prev2].replace('| **上上版** |', '| **历史版** |', 1)

new_row = ('| **当前版本** | 本机 **v2.51**（第九十轮·**三条待裁由用户结案：T-14 两个安东尼奥＝同名异人／'
           'T-15 救赎面具仿造品两张·主角自造的那张不算／T-16 拜占奥试验体不是终极体只是「接近」＋「伦道夫」同姓巧合保留**：'
           '① §3.2 安东尼奥条末加 **同名异人结案注**（限定语必带·不合并不互指不埋伏笔·不解释为转世／误记／借名）；'
           '② §8.1 清算者块防误判① 与 §7.2 两廷造神块防误判④ 标结案；'
           '③ §10.4 新 **「一件真品、两张仿品、一张自造」** 块（真品【救赎】＝阿瑞斯／仿冒品甲＝白袍男人 L2232／'
           '仿冒品乙＝原文未给／主角自造＝不计入两张）；④ §7.2「口子一」改写为 **不是终极体、只到「接近」**'
           '（判据＝处置方式：终极体教廷销毁不掉）＋§7.1 时序闭合后加 **跨廷边界**（四级阶梯不倒推拜占奥）；'
           '⑤ §11.1 P6 #5 与 §3.1 #5 卡妙女皇条改 **巧合保留**（确名·同姓偶合·非笔误）；'
           '⑥ 附录 A **T-14／T-15／T-16 结案**、现状行（待裁 13→10 条）与末句重排；⑦ §11.5 登记 4 项；'
           '⑧ **一处纠错**：T-15 原引「前传 L2238」有误，实为 **L2232**） | 2026-11-20 · 第九十轮 |')
L.insert(i_cur, new_row)

s = '\n'.join(L)

# 纠错档案追加（插在第四节表末，即「**规矩**：任何行号写入设定集前」之前）
anchor = '**规矩**：任何行号写入设定集前'
row = ('| **T-15 所引行号误标（v2.51）** | 附录 A 与 v2.50 登记记「两张仿冒品」出自**前传 L2238** | '
       '原文前传 **L2232**「我这张虽然是黑暗圣物『救赎面具』的两张渀冒品之一」；**L2238** 实为「白袍男人竟然点了点头……你想要？」 | '
       '凭上下文印象取值：该场从 L2227 白袍人出场一路到 L2245 亮红手套，**「两张仿冒品」在第四段而非末段**；'
       '标号时按「这一段的话」顺手记成中段行号，未逐字回查。教训：**凡引「两句对话之间的一句」必须回原文定位，不得按场景估行**；'
       '已改附录 A 与 v2.51 登记块 |\n\n')
assert s.count(anchor) == 1
s = s.replace(anchor, row + anchor)

open(P, 'wb').write(s.encode('utf-8'))
print('ledger ok, lines=%d' % (s.count('\n') + 1))
