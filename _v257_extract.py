# -*- coding: utf-8 -*-
"""v2.57：把设定集内所有版本更新说明迁至《天神下凡设定集版本更新说明集》"""
import shutil

SET = '天神下凡设定集_归纳整理版_v2.57.md'
NEW = '天神下凡设定集版本更新说明集.md'

s = open(SET, 'rb').read().decode('utf-8').replace('\r\n', '\n')
shutil.copyfile(SET, '_bak_v256_before_split.md')

# ---------- 切出三段版本说明 ----------
A0 = s.find('> 更新时间戳：')
M0 = s.find('**版本**：v1.2-r1')
SEC0 = s.find('\n---\n\n## 0. 整理说明')
assert 0 < A0 < M0 < SEC0, (A0, M0, SEC0)

HEAD = s[A0:M0]
META = s[M0:SEC0]
RV0 = META.find('**修订记录**：')
assert RV0 > 0
META_KEEP = META[:RV0]
REVISION = META[RV0:]

C0 = s.find('### 11.5 交付与后续')
REG0 = s.find('#### v2.49 登记｜取杯之夜', C0)
C12 = s.find('## 12. 历史章（v1.67 新增', REG0)
assert 0 < C0 < REG0 < C12
S115_KEEP = s[C0:REG0]
REG = s[REG0:C12]

print('HEAD 字符', len(HEAD), '行', HEAD.count('\n'))
print('REVISION 字符', len(REVISION), '行', REVISION.count('\n'))
print('REG 字符', len(REG), '行', REG.count('\n'))
print('11.5 保留行', S115_KEEP.count('\n'))

# ---------- 组装新文档 ----------
FRONT = '''# 天神下凡设定集版本更新说明集

> **性质**：本集是《天神下凡设定集·归纳整理版》的**版本说明外置卷**。2026-11-23（v2.57）依用户令新建——「**将设定集中所有版本更新的说明文字全部迁移到新文档中，后续的更新说明也放入该新文档不再放入设定集中（设定集只保留最新的版本号和时间戳）。避免更新说明越来越多导致设定集越来越臃肿**」。
> **来源**：自设定集**一次性迁出**三类文字——① 头部「更新时间戳」**49 条**（v2.56 → v1.0）＋「v1.76 历版戳逐字留档」1 条；② 「**修订记录**」段（v1.0 → v2.52 逐版补录）；③ §11.5「**分版登记**」**21 块**（v2.49 及以前）。**原文一字不改，只换位置**；历史说明保留当时表述，后续更正以最新版为准。
> **边界（什么不迁）**：设定集正文内的「**#### vX.XX 补注｜…**」块属**设定内容**（某条设定在哪一版补入、判定依据为何），**不是版本说明**，留在原处不迁；§11.5 的三条「交付与后续」亦留原处；`设定集_裁定台账.md` 的版本四行**不迁**（台账是单一事实源）。
> **现行版本**：**v2.57**｜2026-11-23（GMT+8）｜对应设定集 `天神下凡设定集_归纳整理版_v2.57.md`
> **追加规矩**（设定集 §0.6 第四十六款）：每次升版——① 「一、版本戳」**顶部**加一行（含日期／版本／要点）；② 需要分项登记时，在「三、分版登记」**顶部**加块；③ 设定集头部**只改那一行的版本号与日期**，不写要点；④ 台账仍按原规矩滚动，不迁。

---

## 一、版本戳（最新在上 · v2.57 → v1.0）

> 更新时间戳：2026-11-23（GMT+8）｜**v2.57**｜**第九十六轮：版本说明外置**——依用户令新建本说明集，自设定集一次性迁出头部「更新时间戳」**49 条**＋「v1.76 历版戳逐字留档」1 条、「修订记录」段（v1.0–v2.52）、§11.5「分版登记」**21 块**（v2.49 及以前）；设定集自此**只记版本号与时间戳**；§0.6 新立**第四十六款「版本说明外置」**；正文内「#### vX.XX 补注」块属设定内容、**不迁**｜2026-11-23 |

'''

MID1 = '''
---

## 二、修订记录（v1.0–v2.52 · 原序保真 · 原文一字不改）

'''

MID2 = '''
---

## 三、分版登记（v2.49 及以前 · 共 21 块 · 原文一字不改）

'''

new_doc = FRONT + HEAD.rstrip('\n') + '\n' + MID1 + REVISION.rstrip('\n') + '\n' + MID2 + REG.rstrip('\n') + '\n'
open(NEW, 'wb').write(new_doc.replace('\n', '\r\n').encode('utf-8'))
print('新文档写入', len(new_doc.encode('utf-8')), 'bytes, 行', new_doc.count('\n') + 1)

# ---------- 重建设定集 ----------
STAMP = ('> **v2.57**｜2026-11-23（GMT+8）｜**版本更新说明已外置**：历次版本戳（49 条）、修订记录（v1.0–v2.52）与分版登记（21 块）'
         '已全部迁至《**天神下凡设定集版本更新说明集**》，本稿自此**只记版本号与时间戳**（§0.6 第四十六款）｜2026-11-23 |\n\n')

META_NEW = META_KEEP.replace('**版本**：v1.2-r1（封圣制度补遗版 · 终局裁定同步）',
                             '**版本**：v2.57（2026-11-23 · 版本说明外置版；历次修订记录见《天神下凡设定集版本更新说明集》「二、修订记录」）')
assert META_NEW != META_KEEP

RV_POINTER = ('> **历次修订记录**（v1.0–v2.52，逐版补录）：**已外置**，见《天神下凡设定集版本更新说明集》「二、修订记录」；'
              '原文迁出，一字未改。\n')

S115_POINTER = ('> **分版登记（v2.49 及以前，共 21 块）已外置**：见《天神下凡设定集版本更新说明集》「三、分版登记」。'
                '本节自此只留「交付与后续」三项；每版新增的分项登记一律写入该说明集，**不再回写本稿**（§0.6 第四十六款）。\n\n')

new_set = (s[:A0] + STAMP + META_NEW.rstrip('\n') + '\n\n' + RV_POINTER
           + s[SEC0:C0] + S115_KEEP + S115_POINTER + s[C12:])

open(SET, 'wb').write(new_set.replace('\n', '\r\n').encode('utf-8'))
print('设定集重建', len(new_set.encode('utf-8')), 'bytes, 行', new_set.count('\n') + 1)
