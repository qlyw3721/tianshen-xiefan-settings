def rep(old, new, tag):
    global s
    c = s.count(old)
    assert c == 1, "[%s] count=%d" % (tag, c)
    s = s.replace(old, new)
    print("OK rep:", tag)


def ins(anchor, block, tag):
    """在 anchor 之前插入 block"""
    global s
    c = s.count(anchor)
    assert c == 1, "[%s] anchor count=%d" % (tag, c)
    s = s.replace(anchor, block + anchor)
    print("OK ins:", tag)


def ins_after(anchor, block, tag):
    global s
    c = s.count(anchor)
    assert c == 1, "[%s] anchor count=%d" % (tag, c)
    s = s.replace(anchor, anchor + block)
