# -*- coding: utf-8 -*-
"""v2.67 第二节：莱辛葛/索尔邦撤郡复原、泰坦块补哈维、树表与地图用字"""
import io

P = "天神下凡设定集_归纳整理版_v2.66.md"
lines = io.open(P, encoding="utf-8", newline="").read().split("\r\n")

def sub1(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, "[%s] got %d" % (tag, len(idx))
    lines[idx[0]] = lines[idx[0]].replace(old, new)

# --- 1. §1.5.10 标题 + 更正块 ---
old_h = "#### 1.5.10 莱辛葛郡（北境高原牧区）（v1.63 新增）"
i = lines.index(old_h)
lines[i] = "#### 1.5.10 莱辛葛地区（北境高原牧区）（v1.63 立 · **v2.67 撤郡复原**）"

NOTE10 = """> **v2.67 更正（用户令「把你原创去掉，总数落在 23 个」）**：本节 v1.63 曾「定莱辛葛为神圣帝国北境之一郡」——**此设定层升格于 v2.67 撤回**。原文（前传 **L127**）只作「**莱辛葛地区**产的蓝莓奶酪」，**无一字作「郡」**。**处置**：① 莱辛葛回归「**地区**」，**不占神圣帝国二十三郡之席**（§1.2.0.2 v2.67）；② 本节以下文字中的「**郡**」字，一律读作「**地区**」，**旧段不回溯逐句改写**（承 §0.6 第四十九款「旧段不回溯」之例）；③ 本节所述**物产机制仍然成立**——「一罐奶酪划定一道边界」说的是**产区的边界**，不是**政区的边界**；④ §1.5.8「莱辛葛高原领」（十大领地）与本地区**同名异地级**，各记各的。"""

# 在标题后的空行处插入块（标题下一行必为 ''）
assert lines[i + 1] == "", repr(lines[i + 1])
lines[i + 1:i + 2] = ["", NOTE10, ""]

# --- 2. §1.5.11 标题 + 更正 ---
old_h2 = "#### 1.5.11 索尔邦郡 · 索尔邦神学院（v1.67 新增）"
j = lines.index(old_h2)
lines[j] = "#### 1.5.11 索尔邦地区 · 索尔邦神学院（v1.67 立 · **v2.67 撤郡**）"

NOTE11 = """> **v2.67 更正（用户令「把你原创去掉，总数落在 23 个」）**：① **「索尔邦郡」之「郡」字系 v2.66 增设，v2.67 撤销**——本节以下「索尔邦郡」一律读作「**索尔邦**」或「**索尔邦地区**」，**不占二十三郡之席**；② **同时更正本节旧陈述**：v1.67 记「前后传原文 txt 无『索尔邦郡』与『索尔邦神学院』之逐字表述（本版检索未得）」——**「索尔邦郡」三字确无，但「索尔邦」地名原文有**：前传 **L998** 逐字「他甚至花费不少时间查询资料研究了**索尔邦**一个建立于四百年前的古老神学院」。**原文有名而不作郡**，与**原文彻底无载**，是两件事——旧记「检索未得」属**检索口径失准**（只查全名、未查词根），v2.67 更正。**神学院之名仍为设定层定名**（原文只作「一个……古老神学院」，未給专名），此点不变。"""

assert lines[j + 1] == "", repr(lines[j + 1])
lines[j + 1:j + 2] = ["", NOTE11, ""]

# --- 3. 树表 / 地图 用字 ---
sub1("| 2 | **奥克塔维娅**（Octavia） | 神圣帝国·**莱辛葛郡**高原 |", "| 2 | **奥克塔维娅**（Octavia） | 神圣帝国·**莱辛葛地区**高原 |", "tree")
cnt = sum(l.count("●莱辛葛郡（北境牧区）") for l in lines)
assert cnt == 3, cnt
lines = [l.replace("●莱辛葛郡（北境牧区）", "●莱辛葛地区（北境牧区）") for l in lines]

# --- 4. 泰坦块补哈维郡 ---
anchor = "| **米奇厄尔冲积平原** |"
k = [i for i, l in enumerate(lines) if l.startswith(anchor)]
assert len(k) == 1, k
HAVY = "| **哈维郡** | 「打着**来自哈维郡省来美洛蒂郡探亲**幌子的奥古斯丁」 | 后传 **L4826** | **补登**（v2.67）：泰坦郡省。奥古斯丁以「哈维郡探亲」为幌子赴美洛蒂郡晚宴——**幌子要通，两郡须同国**；美洛蒂在泰坦境内（L4821「在**泰坦境内**破例」），故哈维亦属泰坦【归属·推定】 |"
lines.insert(k[0], HAVY)

# --- 5. 泰坦块防误判补一条 ---
p = [i for i, l in enumerate(lines) if l.startswith("> **防误判**【续补·原创】：① 「果戈理雕像」为**红鞭骑士团内支队长名**")]
assert len(p) == 1, p
lines[p[0]] = lines[p[0]].replace(
    "④ 南蜥城「地上龙族」是**当地迷信**",
    "④ **哈维郡归属为推定**（据 L4821「泰坦境内」与 L4826 幌子逻辑），非原文直书，引时须带「推定」二字；⑤ 南蜥城「地上龙族」是**当地迷信**")

io.open(P, "w", encoding="utf-8", newline="").write("\r\n".join(lines))
print("OK lines=", len(lines))
