# -*- coding: utf-8 -*-
import io

BASE = "E:/天神下凡/"

def load(p):
    raw = io.open(BASE + p, "rb").read().decode("utf-8")
    return raw.split("\r\n")

def save(p, lines):
    txt = "\r\n".join(lines)
    io.open(BASE + p, "wb").write(txt.encode("utf-8"))
    print(p, "写入完成，", len(lines), "行")

def rep(lines, old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx), [i+1 for i in idx][:5])
    lines[idx[0]] = lines[idx[0]].replace(old, new)

def insert_after(lines, anchor, block, tag, blank=True):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx), [i+1 for i in idx][:5])
    i = idx[0]
    payload = block.split("\n")
    if blank:
        payload.append("")
    lines[i+1:i+1] = payload

