def save(p,l): io.open(p,"wb").write("\r\n".join(l).encode("utf-8"))
def first(lines, pred, tag):
    idx=[i for i,l in enumerate(lines) if pred(l)]
    assert idx, (tag,"not found")
    return idx[0]

