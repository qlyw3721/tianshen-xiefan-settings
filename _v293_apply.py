def rep(old, new, tag, expected=1):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == expected, (tag, len(idx))
    for i in idx:
        lines[i] = lines[i].replace(old, new)
    print('rep ok', tag, 'x', len(idx))

def insert_after_line(anchor, add, tag, blank_after=0):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx))
    i = idx[0]
    ins = list(add)
    # 保证块前有空行
    if lines[i+1].strip() != '':
        ins = [''] + ins
    lines[i+1:i+1] = ins
    print('insert ok', tag, 'at', i+1)

