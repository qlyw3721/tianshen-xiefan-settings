def rep(old, new, tag):
    global t
    c = t.count(old)
    assert c == 1, 'REP[%s] 命中 %d 次' % (tag, c)
    t = t.replace(old, new, 1)
    log.append('REP ' + tag)


def ins_before(anchor, block, tag):
    global t
    c = t.count(anchor)
    assert c == 1, 'INS_BEFORE[%s] 命中 %d 次' % (tag, c)
    t = t.replace(anchor, block + anchor, 1)
