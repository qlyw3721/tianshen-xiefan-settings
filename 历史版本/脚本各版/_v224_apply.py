def rep(old, new, tag):
    global t
    n = t.count(old)
    assert n == 1, "[%s] 期望 1 处，实际 %d" % (tag, n)
    t = t.replace(old, new, 1)
    print("  OK  " + tag)


def ins_before(anchor, block, tag):
    global t
    n = t.count(anchor)
    assert n == 1, "[%s] 锚点期望 1 处，实际 %d" % (tag, n)
    t = t.replace(anchor, block.replace("\n", "\r\n") + anchor, 1)
    print("  OK  " + tag)


