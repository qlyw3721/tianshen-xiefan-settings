# -*- coding: utf-8 -*-
import io
P = "设定集_裁定台账.md"
t = io.open(P, encoding="utf-8", newline="").read()
assert t.count("\r\n") == 0

def rep(old, new, tag):
    global t
    n = t.count(old)
    assert n == 1, "[%s] 期望1处，实际%d" % (tag, n)
    t = t.replace(old, new, 1)
    print("  OK " + tag)

rep("| **当前版本** | 本机 **v2.24**（第六十三轮", "| **上一版** | 本机 **v2.24**（第六十三轮", "旧当前版本行降为上一版")

