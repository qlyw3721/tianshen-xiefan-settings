          "**新规首用**：「什么是异端」「不认可的就是异端」「铜钥匙」三串关键词在本机节本内 **0 命中** → 判**节本缺失**、非「原文没有」，故**不标行号**，标【原文·节本缺失·待完整版补】；"
          "立 §7.2 章首权威条：三条机制（判准即「不认可」／主体为两大教廷共有／门槛低到**不信仰即可入罪**）＋四层后果（可政治化·不可诉·**可互换**·可撤销）＋四层分工（源头·结果清单·位阶·顶点）＋七条写作纪律（**一律写「被判定为异端」，不写「某人是异端」**）；"
