# -*- coding: utf-8 -*-
"""V2.2 口径切换的文档同步：说明集 / 台账 / 归档索引。只改版本号记述，不动设定内容。"""
import io

BASE = 'E:/天神下凡/'

# ---------- 1) 说明集 ----------
p = BASE + '天神下凡设定集版本更新说明集.md'
S = io.open(p, 'r', encoding='utf-8', newline='').read().split('\r\n')

old = S[5]
assert old.startswith('> **现行版本**：**v2.109**'), old[:40]
S[5] = old.replace(
    '> **现行版本**：**v2.109**｜2026-11-26（GMT+8）｜对应设定集 `天神下凡设定集_归纳整理版_v2.109.md`｜',
    '> **现行版本**：**V2.2**｜2026-11-26（GMT+8）｜对应设定集 `天神下凡设定集_归纳整理版_V2.2.md`'
    '｜**版本号口径**：自本版起只保留小数点后 1 位｜', 1)
assert 'V2.2' in S[5]

tick = (
    '> **V2.2 版本号口径变更**：用户 2026-11-26 令「**版本号只保留小数点后 1 位，'
    '从现在开始，当前版本号更正为 V2.2**」。自本版起改用**一位小数序列**（V2.2 → V2.3 … V2.9 → V3.0）；'
    '原 **v1.0–v2.109** 三位小数序列、历史归档件名、既有「#### vX.XX 补注」块标题**一律保留原编号，不回溯改名**；'
    '本版**设定内容与原 v2.109 完全一致**，只改版本号、文件名与口径说明；为免与旧 v2.1x 混淆，'
    '**V2.1 不单独发行**，切换即自 V2.2 起。'
)
S.insert(6, tick)

io.open(p, 'w', encoding='utf-8', newline='').write('\r\n'.join(S))
print('说明集：现行版本行已改 V2.2，口径变更已登记于 L7')

# ---------- 2) 台账 ----------
p = BASE + '设定集_裁定台账.md'
T = io.open(p, 'r', encoding='utf-8', newline='').read().split('\r\n')
row = T[62]
assert row.startswith('| **当前版本** | v2.109 |'), row[:40]
row = row.replace('| **当前版本** | v2.109 |', '| **当前版本** | **V2.2**（原 v2.109） |', 1)
row = row.replace('24,030 行／3,822,504 B', '24,030 行／3,822,718 B', 1)
row = row.rstrip(' |') + '｜**V2.2 口径**：用户 2026-11-26 令版本号只保留小数点后 1 位、当前版更正为 V2.2；仅改名不改内容，原 v1.0–v2.109 不回溯改名 |'
T[62] = row
io.open(p, 'w', encoding='utf-8', newline='').write('\r\n'.join(T))
print('台账：当前版本行已改 V2.2；字节数校正 3,822,718')

# ---------- 3) 归档索引 ----------
p = BASE + '历史版本/00_归档索引.md'
Z = io.open(p, 'r', encoding='utf-8', newline='').read()
old9 = '| `设定集各版\\` | 设定集历版 md／docx（`v1.0` → `v2.109`，含 `v1.66整合`） | 235 |'
assert old9 in Z, 'index L9 pattern missing'
Z = Z.replace(old9, '| `设定集各版\\` | 设定集历版 md／docx（`v1.0` → `v2.109` → `V2.2`，含 `v1.66整合`；**V2.2 起版本号改一位小数**） | 235 |', 1)

old17 = '**合计 805 件／660 MB**（v2.109 收口新增 5 件：'
assert old17 in Z
Z = Z.replace(old17,
    '**V2.2 版本号口径切换**（2026-11-26，用户令「版本号只保留小数点后 1 位，当前版本更正为 V2.2」）：'
    '现行版 `v2.109` → `V2.2`，**仅改名与口径说明，内容一字未动**，不产生归档件、计数不变；'
    '原 v1.0–v2.109 归档件不改名；**合计 805 件／660 MB**（v2.109 收口新增 5 件：', 1)

io.open(p, 'w', encoding='utf-8', newline='').write(Z)
print('索引：范围描述与口径说明已补，计数不变 235／353／805')
