def rep(old, new, tag):
    global s
    c = s.count(old)
    assert c == 1, (tag, c)
    s = s.replace(old, new)
    print('ok', tag)


def rep_block(start, end, new, tag):
    """替换 start 起、end 止（含 end 整行）的整块"""
    global s
    i = s.find(start)
    assert i > 0, ('start', tag)
    j = s.find(end, i)
    assert j > i, ('end', tag)
    j = j + len(end)
    s = s[:i] + new.rstrip('\n') + s[j:]
    print('ok block', tag)


