def idx_of(prefix, start=0):
    hits = [i for i in range(start, len(L)) if L[i].startswith(prefix)]
    assert len(hits) == 1, (prefix, hits[:5])
    return hits[0]


def ins_after(prefix, text):
    i = idx_of(prefix)
    L.insert(i + 1, text)
    print('ok ins_after', prefix[:24])


def ins_before(prefix, text):
    i = idx_of(prefix)
    L.insert(i, text)
    print('ok ins_before', prefix[:24])


def repl_line(prefix, text):
    i = idx_of(prefix)
    L[i] = text
    print('ok repl', prefix[:24])


