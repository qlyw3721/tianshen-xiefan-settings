# -*- coding: utf-8 -*-
"""v2.57 第二批：文末补记补录外置 + §11.5 指针 + §0.6 第四十六款 + 六步第 6 条"""
import shutil

SET = '天神下凡设定集_归纳整理版_v2.57.md'
NEW = '天神下凡设定集版本更新说明集.md'
shutil.copyfile(SET, '_bak_v257_before_b.md')
shutil.copyfile(NEW, '_bak_hist_before_b.md')

s = open(SET, 'rb').read().decode('utf-8').replace('\r\n', '\n')


def rep(old, new, tag):
    global s
    c = s.count(old)
    assert c == 1, (tag, c)
    s = s.replace(old, new)
    print('ok', tag)


# ---- 1. 迁出文末补记与补录 ----
i = s.find('\n**v1.1 补记**：')
j = s.find('\n## 17. 哲学与神学', i)
assert 0 < i < j
BLOCK = s[i:j]
s = (s[:i]
     + '\n> **历版补记（v1.1／v1.2）与补录（v1.73–v1.90，共 18 段）已外置**：见《天神下凡设定集版本更新说明集》「二、修订记录·续」。'
       '本稿不再保留历版补记；各词条现行表述与 §16 进度表为准。\n\n'
     + s[j + 1:])
print('迁出文末块字符', len(BLOCK), '行', BLOCK.count('\n'))

# ---- 2. 追加到说明集「二」末尾（三、之前） ----
nd = open(NEW, 'rb').read().decode('utf-8').replace('\r\n', '\n')
anchor = '\n---\n\n## 三、分版登记'
k = nd.find(anchor)
assert k > 0
SUB = '\n### （续）文末补记与补录（v1.1／v1.2 补记 · v1.73–v1.90 补录 · 原序保真）\n'
nd = nd[:k] + SUB + BLOCK.rstrip('\n') + '\n' + nd[k:]
open(NEW, 'wb').write(nd.replace('\n', '\r\n').encode('utf-8'))
print('说明集更新', len(nd.encode('utf-8')), 'bytes')

# ---- 3. 设定集头部加「更新时间戳：」 ----
rep('> **v2.57**｜2026-11-23（GMT+8）｜**版本更新说明已外置**',
    '> 更新时间戳：2026-11-23（GMT+8）｜**v2.57**｜**版本更新说明已外置**',
    'stamp')

# ---- 4. §11.5 指针移到分隔线之前 ----
rep('---\n\n\n> **分版登记（v2.49 及以前，共 21 块）已外置**',
    '> **分版登记（v2.49 及以前，共 21 块）已外置**',
    's115-move1')
rep('（§0.6 第四十六款）。\n\n## 12. 历史章',
    '（§0.6 第四十六款）。\n\n---\n\n## 12. 历史章',
    's115-move2')

# ---- 5. §0.6 第四十六款 ----
ANCHOR45 = '> 一句：**你给要点，我补缝；缝补在明处，不在暗处。**\n'
NEW46 = ANCHOR45 + '''
**四十六、版本说明外置（2026-11-23 立 · 用户令）**

> **立款缘由**：用户 2026-11-23 令——「**新建一个文档（标题就叫天神下凡设定集版本更新说明集），将设定集中所有版本更新的说明文字全部迁移到新文档中，后续的更新说明也放入该新文档不再放入设定集中（设定集只保留最新的版本号和时间戳）。避免更新说明越来越多导致设定集越来越臃肿**」。v2.57 已一次性迁出三类历史说明（头部戳 49 条＋1 条留档、修订记录段、§11.5 分版登记 21 块、文末补记与补录 18 段），本款管**以后不再长回来**。

**一、三分天下（谁写哪里）**

| 文档 | 装什么 | 不装什么 |
| --- | --- | --- |
| **设定集**（本稿） | 设定正文；词条内「#### vX.XX 补注」块（属**设定内容**）；头部**一行**版本号＋时间戳＋指针 | 历版戳、修订记录、分版登记 |
| **《天神下凡设定集版本更新说明集》** | ① 版本戳（每版一行，最新在上）；② 修订记录（逐版补录）；③ 分版登记（逐版分项表） | 设定正文；待裁清单本体 |
| **`设定集_裁定台账.md`** | 用户裁定四行版本区＋裁定行（单一事实源） | 逐版工作细节 |

**二、每版四步（升版即照办，不攒批）**

1. 说明集「一、版本戳」**顶部**加一行：日期 ｜ 版本 ｜ 要点（**能省则省**，不复制正文）。
2. 需分项登记时，说明集「三、分版登记」**顶部**加块（`#### vX.XX 登记｜…`）。
3. 设定集头部**只改那一行**的版本号与日期，**不写要点**。
4. 台账版本四行照旧滚动（**不迁、不减**——台账是事实源，不是说明集）。

**三、边界（防误迁）**

| # | 不迁 | 缘由 |
| --- | --- | --- |
| 1 | `#### vX.XX 补注｜…` 块 | 它是**设定内容**（判定依据、行号、分层标注），迁走即断链 |
| 2 | §11.1／§14.9 的 `#### vX.XX 登记` 块 | 是**裁决表与红线的本体**（两存待裁、异写、越界登记），不是版本说明 |
| 3 | §11.5「交付与后续」三条 | 是**文档性质说明**，不属更新史 |
| 4 | 用户原话逐字块 | 迁出时**一字不动**；说明集内亦不得改写 |

**四、三处指针（缺一即视为违规）**

| 位置 | 写什么 |
| --- | --- |
| 设定集头部 | 一行戳 ＋「版本更新说明已外置，见《天神下凡设定集版本更新说明集》」 |
| 设定集 §11.5 | 「分版登记已外置」指针 |
| 说明集开头 | 「现行版本」＋对应设定集文件名 |

> 一句：**设定集记事，说明集记史；记事的不背史，记史的不管事。**
'''
rep(ANCHOR45, NEW46, 'clause46')

# ---- 6. 六步第 6 条 ----
rep('6. **登记**：本词条第六节进度表回填、异文／冲突交 §11.1 两存待裁、修订记录与版本戳同步。',
    '6. **登记**：本词条第六节进度表回填、异文／冲突交 §11.1 两存待裁、**修订记录与版本戳写入《天神下凡设定集版本更新说明集》**（§0.6 第四十六款）——设定集头部只改版本号与日期，**不写要点**。',
    'sixstep')

# ---- 7. 第四十四款第 3 步与第四十五款处置表的指向 ----
rep('改正文 ＋ 附录 A 标**已结案** ＋ 台账记一行 ＋ §11.5 登记：**不隔轮、不攒批**',
    '改正文 ＋ 附录 A 标**已结案** ＋ 台账记一行 ＋ **说明集登记**（§0.6 第四十六款；原「§11.5 登记」自 v2.57 起外置）：**不隔轮、不攒批**',
    'c44-step3')
rep('| **登记** | 有料但不入正文（异写、原文误书、时序张力、数字巧合） | §11.2／§11.5／台账纠错档 |',
    '| **登记** | 有料但不入正文（异写、原文误书、时序张力、数字巧合） | §11.2／《版本更新说明集》／台账纠错档 |',
    'c45-reg')

open(SET, 'wb').write(s.replace('\n', '\r\n').encode('utf-8'))
print('设定集写入', len(s.encode('utf-8')), 'bytes, 行', s.count('\n') + 1)
