# -*- coding: utf-8 -*-
import json, zipfile, os

def t(title, children=None, tid=None):
    d = {"id": tid or ("n" + str(abs(hash(title)) % 10**10)), "class": "topic", "title": title}
    if children:
        d["children"] = {"attached": children}
    return d

def make(path, root_title, branches):
    content = [{
        "id": "sheet-1",
        "class": "sheet",
        "title": "画布 1",
        "rootTopic": t(root_title, branches, tid="root-topic"),
    }]
    meta = {"creator": {"name": "WorkBuddy", "version": "1.0"}}
    manifest = {"file-entries": {"content.json": {}, "metadata.json": {}}}
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('manifest.json', json.dumps(manifest, ensure_ascii=False))
        z.writestr('metadata.json', json.dumps(meta, ensure_ascii=False))
        z.writestr('content.json', json.dumps(content, ensure_ascii=False))
    print('made', path, os.path.getsize(path), 'bytes')

