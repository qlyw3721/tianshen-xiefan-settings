# ---------- 4. 人物志正文转块 ----------
EL = e.split('\n')
start = None
for i, l in enumerate(EL):
    if l.strip() == '## 卷首 · 体例':
        start = i
        break
assert start is not None, 'no 卷首'

out = []
for l in EL[start:]:
    t = l.rstrip()
    if t.startswith('## '):
        out.append('')
        out.append('**' + t[3:].strip() + '**')
        out.append('')
    elif t.startswith('### '):
        out.append('')
        out.append('**' + t[4:].strip() + '**')
        out.append('')
    elif t.strip() == '---':
        continue
    else:
        out.append(t)

body = '\n'.join(out)
body = re.sub(r'\n{3,}', '\n\n', body).strip('\n')

