def replace_line(prefix, new, tag):
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, "[%s] got %d" % (tag, len(idx))
    lines[idx[0]] = new
    return idx[0]

def sub_in_line(prefix, old, new, tag):
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
