# -*- coding: utf-8 -*-
import io

P = "天神下凡设定集_归纳整理版_v2.70.md"
lines = io.open(P, encoding="utf-8", newline="").read().split("\r\n")


def sub1(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]] = lines[idx[0]].replace(old, new)
    print("OK sub", tag, idx[0] + 1)


def insert_after(prefix, block, tag):
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0] + 1:idx[0] + 1] = block.split("\n") + [""]
    print("OK after", tag, idx[0] + 1)


def insert_before(prefix, block, tag):
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]:idx[0]] = block.split("\n") + [""]
    print("OK before", tag, idx[0] + 1)


def replace_range(start_prefix, end_prefix, block, tag):
    a = [i for i, l in enumerate(lines) if l.startswith(start_prefix)]
    b = [i for i, l in enumerate(lines) if l.startswith(end_prefix)]
    assert len(a) == 1 and len(b) == 1 and a[0] < b[0], (tag, a, b)
    lines[a[0]:b[0]] = block.split("\n") + [""]
    print("OK range", tag, a[0] + 1, b[0] + 1)


