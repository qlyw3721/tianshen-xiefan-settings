def loc(prefix, tag, nth=None):
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    if nth is None:
        assert len(idx) == 1, (tag, len(idx), idx[:5])
        return idx[0]
    assert len(idx) > nth, (tag, len(idx), idx[:5])
    return idx[nth]

def setline(prefix, new, tag):
    L[loc(prefix, tag)] = new

