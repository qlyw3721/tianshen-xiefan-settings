# 三、v1.90 防误判⑥ 补交叉引用（主院何以与整体同名）
old = '⑥ 「脉代奥拉**神学院**」与「脉代奥拉**修道院／主修道院**」为**同一实体之两称**（前传 L2467「脉代奥拉神学院」／L2509「脉代奥拉主修道院」；后传 L40「脉代奥拉修道院院长」）——院长之位只有一个，**不得因两称而设两位院长**。'
idx = [k for k, l in enumerate(L) if l == old]
assert len(idx) == 1, ('防误判⑥', len(idx))
L[idx[0]] = old + ' **v2.75 通则补**：两称之所以两称，见 §1.5.13 五（主院足够强大，其名可代表整个神学院）；院长仍只一位。'

