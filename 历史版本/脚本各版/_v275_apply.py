i = loc(anchor, '五连带')
L[i] = L[i].replace('**五、连带', '**六、连带', 1)
anchor6 = '**六、亚瑟多瑙河与夜蔷薇大船（v2.46 · 用户补＋原文旁证）**'
j = loc(anchor6, '六亚瑟')
L[j] = L[j].replace('**六、亚瑟', '**七、亚瑟', 1)

