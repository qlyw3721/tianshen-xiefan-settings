# -*- coding: utf-8 -*-
import io

P = '天神下凡设定集_归纳整理版_v2.74.md'
L = io.open(P, encoding='utf-8').read().split('\n')


def loc(s, tag):
    idx = [i for i, l in enumerate(L) if l == s]
    assert len(idx) == 1, (tag, len(idx), idx[:5])
    return idx[0]


# 一、主稿头部版本戳：上轮 v2.74 漏改，本轮一并升 v2.75
for i, l in enumerate(L[:10]):
    if '更新时间戳' in l:
        assert 'v2.73' in l, ('head stamp', l[:80])
        L[i] = l.replace('**v2.73**', '**v2.75**')
    if l.startswith('**版本**：'):
        assert 'v2.73' in l, ('head ver', l[:80])
        L[i] = '**版本**：v2.75（2026-11-24）'

# 二、§1.5.13 新增"五、神学院与修道院的关系"，原五/六顺延为六/七
