def loc(prefix, tag, nth=0):
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    assert len(idx) > nth, (tag, len(idx), idx[:6])
    return idx[nth]


def insert_after(prefix, block, tag, nth=0):
    i = loc(prefix, tag, nth) + 1
    L[i:i] = block
    print('  插入', tag, '@L%d' % (i + 1), len(block), '行')


