import io

P = '天神下凡设定集_归纳整理版_v2.77.md'
L = io.open(P, encoding='utf-8').read().split('\n')

def loc(prefix, tag, nth=0):
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    assert len(idx) > nth, (tag, len(idx), idx[:5])
    if nth == 0:
        assert len(idx) == 1, (tag, len(idx), idx[:5])
    return idx[nth]

def ins(i, lines):
    L[i:i] = lines

def rep(old, new, tag):
    idx = [i for i, l in enumerate(L) if old in l]
    assert len(idx) == 1, (tag, len(idx), idx[:5])
    L[idx[0]] = L[idx[0]].replace(old, new)
    print('OK', tag)

