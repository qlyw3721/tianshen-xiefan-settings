import io, os, shutil
BASE = 'E:/天神下凡/'

def readlines(p):
    return io.open(p, encoding='utf-8').read().split('\n')

def writelines(p, lines):
    out = '\r\n'.join(lines)
    assert out.replace('\r\n', '').find('\n') == -1, 'naked LF: ' + p
    io.open(p, 'w', encoding='utf-8', newline='').write(out)

def rep(lines, old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]] = lines[idx[0]].replace(old, new)

