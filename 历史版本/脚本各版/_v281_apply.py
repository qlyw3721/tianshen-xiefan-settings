def rep(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]] = lines[idx[0]].replace(old, new)

def insert_after(anchor, block, tag, blank=False):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx))
    i = idx[0]
    lines[i+1:i+1] = ([''] if blank else []) + block.split('\n')

