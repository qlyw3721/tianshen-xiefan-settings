def insert_after(anchor, block, tag, offset=0):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx))
    i = idx[0] + offset
    lines[i+1:i+1] = block.split('\n')

def insert_before(anchor, block, tag):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]:idx[0]] = block.split('\n')

def rep(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]] = lines[idx[0]].replace(old, new)

