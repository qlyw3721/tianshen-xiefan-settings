def rep(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    i = idx[0]
    parts = lines[i].split(old)
    assert len(parts) == 2, (tag, 'old appears >1 in line')
    lines[i:i+1] = [parts[0] + new.replace('\n', '\x00') + parts[1]]
    lines[i] = lines[i].replace('\x00', '\n')
    # 拆成真正的多行元素，避免裸 LF 混入单个元素
    j = idx[0]
    if '\n' in lines[j]:
        lines[j:j+1] = lines[j].split('\n')

def insert_before(anchor, block, tag):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]:idx[0]] = block

