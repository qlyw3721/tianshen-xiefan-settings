def rep(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    i = idx[0]
    assert lines[i].count(old) == 1, (tag, 'multiple in line')
    lines[i] = lines[i].replace(old, new)

def insert_before(anchor, block, tag):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, len(idx))
    i = idx[0]
    assert lines[i-1].strip() == '', (tag, 'no blank before anchor')
    lines[i:i] = block.split('\n') + ['']

