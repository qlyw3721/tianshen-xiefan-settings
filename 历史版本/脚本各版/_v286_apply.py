def rep(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, 'lines', len(idx))
    i = idx[0]
    assert lines[i].count(old) == 1, (tag, 'multi-in-line')
    lines[i] = lines[i].replace(old, new)

def insert_after(anchor, block, tag):
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, (tag, 'anchor', len(idx))
    i = idx[0]
    assert lines[i+1].strip() == '', (tag, 'need blank after anchor')
    lines[i+1:i+1] = block.split('\n')

