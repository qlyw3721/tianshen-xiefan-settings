def rep(old, new, tag):
    i = find_one(old, tag)
    assert old in lines[i], (tag, 'substr missing')
    lines[i] = lines[i].replace(old, new, 1)

def rep_all(old, new, tag, expect=None):
    cnt = 0
    for i, l in enumerate(lines):
        if old in l:
            lines[i] = l.replace(old, new)
            cnt += 1
    if expect is not None:
        assert cnt == expect, (tag, cnt, expect)

def insert_after(anchor, block, tag, blank=True):
    i = find_one(anchor, tag)
    ins = list(block)
    if blank and (ins and ins[-1].strip() != ''):
        ins.append('')
    lines[i+1:i+1] = ins

