def load(p):
    return io.open(p, "rb").read().decode("utf-8").split("\r\n")

def save(p, lines):
    io.open(p, "wb").write("\r\n".join(lines).encode("utf-8"))

def set_line(lines, needle, new, tag):
    idx = [i for i, l in enumerate(lines) if needle in l]
    assert idx, (tag, "not found")
