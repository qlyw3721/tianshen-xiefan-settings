# ---------- 0) 先归档旧版（哈希核对），避免重蹈 v2.96 覆盖后从 git 恢复 ----------
for ext in ('md', 'docx'):
    src = BASE + '天神下凡设定集_归纳整理版_v2.96.' + ext
    dst = ARCH + '天神下凡设定集_归纳整理版_v2.96.' + ext
    h1 = hashlib.sha256(open(src, 'rb').read()).hexdigest()
    shutil.copyfile(src, dst)
    h2 = hashlib.sha256(open(dst, 'rb').read()).hexdigest()
    assert h1 == h2, ('archive hash mismatch', ext)
    print('archived', ext, h1[:16])

b = io.open(SRC, 'r', encoding='utf-8', newline='').read()
assert '\r\n' in b and '\n' not in b.replace('\r\n', ''), 'not CRLF'
lines = b.split('\r\n')

def rep_line(old, new, tag):
    idx = [i for i, l in enumerate(lines) if old in l]
    assert len(idx) == 1, (tag, len(idx))
    lines[idx[0]] = lines[idx[0]].replace(old, new)

def rep_in(prefix, old, new, tag):
    idx = [i for i, l in enumerate(lines) if prefix in l]
    assert len(idx) == 1, (tag, len(idx))
    assert old in lines[idx[0]], (tag, 'old not found')
    lines[idx[0]] = lines[idx[0]].replace(old, new)

