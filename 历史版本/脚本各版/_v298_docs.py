import io

BASE = 'E:/天神下凡/'

def load(p):
    return io.open(p, 'r', encoding='utf-8', newline='').read().split('\r\n')

def save(p, lines):
    out = '\r\n'.join(lines)
    assert '\n' not in out.replace('\r\n', ''), ('bare LF', p)
    io.open(p, 'w', encoding='utf-8', newline='').write(out)

def rep_start(lines, prefix, new_full, tag):
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert idx, (tag, 'none')
    lines[idx[0]] = new_full

