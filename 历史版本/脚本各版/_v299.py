assert b'\r\n' in raw and b'\n' not in raw.replace(b'\r\n', b''), 'SRC not CRLF'
arch_md = ARCH + '天神下凡设定集_归纳整理版_v2.98.md'
arch_docx = ARCH + '天神下凡设定集_归纳整理版_v2.98.docx'
