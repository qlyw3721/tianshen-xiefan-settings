import io

BASE = 'E:/天神下凡/'

def load(p):
    b = io.open(p, 'r', encoding='utf-8', newline='').read()
    return b, b.split('\r\n')

def save(p, lines):
    out = '\r\n'.join(lines)
    assert '\n' not in out.replace('\r\n', ''), ('bare LF', p)
    io.open(p, 'w', encoding='utf-8', newline='').write(out)

