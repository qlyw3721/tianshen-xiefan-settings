def rn(t):
    return t.replace('庞培', '庞贝').replace('克拉苏', '克拉夫')

def fix(s):
    if s.count('「') != s.count('」') or s.count('『') != s.count('』'):
        return s
    out = []; last = 0
    for m in PROT.finditer(s):
        out.append(rn(s[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(rn(s[last:]))
    return ''.join(out)

