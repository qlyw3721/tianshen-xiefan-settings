def rep(f, old, new, tag):
    raw = open(f, 'rb').read()
    o = old.encode('utf-8'); n = new.encode('utf-8')
    assert raw.count(o) == 1, (tag, raw.count(o))
    open(f, 'wb').write(raw.replace(o, n))
    print('OK', tag)

