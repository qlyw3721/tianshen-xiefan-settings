BASE = 'E:/天神下凡/'

def patch(path, pairs):
    raw = open(path, 'rb').read()
    for old, new, tag in pairs:
        o = old.encode('utf-8')
        n = raw.count(o)
        assert n == 1, (tag, n)
        raw = raw.replace(o, new.encode('utf-8'))
    open(path, 'wb').write(raw)
    print('OK', path.split('/')[-1])

