def patch(path, pairs, tag):
    raw = open(path, 'rb').read()
    for old, new in pairs:
        o = old.encode('utf-8')
        n = raw.count(o)
        assert n == 1, (tag, old[:40], n)
        raw = raw.replace(o, new.encode('utf-8'))
    open(path, 'wb').write(raw)
    chk = open(path, 'rb').read()
    print('OK', tag, 'bytes', len(chk), 'bareLF', chk.count(b'\n') - chk.count(b'\r\n'))


