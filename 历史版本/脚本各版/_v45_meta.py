def load(p):
    return open(p, 'rb').read().decode('utf-8').split('\r\n')


def save(p, lines):
    open(p, 'wb').write('\r\n'.join(lines).encode('utf-8'))
    raw = open(p, 'rb').read()
    print('  saved', p.split('/')[-1], len(raw), 'bytes, bareLF',
          raw.count(b'\n') - raw.count(b'\r\n'))


