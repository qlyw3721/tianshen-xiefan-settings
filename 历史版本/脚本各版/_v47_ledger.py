# -*- coding: utf-8 -*-
import re
# ---------- 台账 ----------
p='设定集_裁定台账.md'
raw=open(p,'rb').read().decode('utf-8')
assert raw.count('\r\n')==raw.count('\n')
lines=raw.split('\r\n')
i=[j for j,l in enumerate(lines) if l.startswith('| **当前版本** | **V4.6**')]
assert len(i)==1,(len(i))
k=i[0]
new=('| **当前版本** | **V4.7**（原序列 v2.109 之后） | 2026-11-27 | **卷二第101–102章＋卷三第001–005章 7 份分析稿复核**：'
 '收确缺 **15 项**（条顿祭司墓志铭 L5685／伊耶塔三件教袍 L5763／《教诲》624 页 L5762·5765·5821／公主小皇冠 L5841–48／'
 '**原文第十席「圣努基帜」L5981**／奥古迦边疆伯爵 L6077／波旁银币抛币定真伪 L6130–35／验证学·莱默尔·迪威尔 L6198／'
 '菲奥娜十二燕子六乌鸦 L6225／训练八科 L6231／苏菲 L6232–33／赫本 L6235–46／火柴盒子＋滴水 L6249–50／'
 '多米诺 499001 L6264–74／荒芜之地 L6319）＋金句 **#229–#238** 十条。'
 '**订正八条**：五百万→**499001**；两块花圃→**一块**；奥古迦五公爵头衔（库内误并「萨森勃兰登堡」）→**五项分列**；'
 '燕子乌鸦「未落地」→**后传已落地**；领袖者意志→主名**领袖意志**；圣努基帜名从原文；《一根思想芦苇》两写照录；墙铭补全中段。'
 '**待裁定 Q-01**：v1.42 第十席＝梅根 vs 原文 L5981 圣努基帜排第十——现行仍以梅根为第十席，只登记并存，不擅改榜单。'
 '**分析方推断不入设定**：F451–F525／F629–F641 编号随稿归档；「第三道大门」「那个女孩」留白不代拟。'
 'md **25,712 行／4,138,306 B／裸 LF 0**；docx **2,430,873 B**；四件套全绿（缺空行 1、表格异常 2 块、连续空行 0）；未上传资料库。 |')
lines[k]=lines[k].replace('| **当前版本** |','| **上一版** |',1)
lines=lines[:k]+[new]+lines[k:]
d='\r\n'.join(lines)
open(p,'wb').write(d.encode('utf-8'))
b=open(p,'rb').read()
assert b.count(b'\n')==b.count(b'\r\n')
print('台账 ok',len(b))

