# -*- coding: utf-8 -*-
import re
# ---------- 台账 ----------
p='设定集_裁定台账.md'
raw=open(p,'rb').read().decode('utf-8')
assert raw.count('\r\n')==raw.count('\n')
lines=raw.split('\r\n')
i=[j for j,l in enumerate(lines) if l.startswith('| **当前版本** | **V4.7**')]
assert len(i)==1,(len(i))
k=i[0]
new=('| **当前版本** | **V4.8**（原序列 v2.109 之后） | 2026-11-27 | **骑士身份更正（用户令）**：'
 '**皇家2号骑士＝16 级（圣骑士阶段）≠ 帝国第二骑士拉法叶**（序位榜，前传 L333），两人不并。'
 '原文五条：后传 L343（10–13 阶配巴思勋章／皇家2号骑士 16 级／帝国 6 大骑士＝圣棺 20 级左右不屑配章）、'
 '后传 L143（皇帝身后黄金重铠面铠）、后传 L1711（大骑士 10／中枢 16／圣棺 20）、前传 L333（拉法叶）、前传 L2371（所罗门钥匙圣铠）。'
 '**三层刻度**：10–13 阶→巴思勋章；16 级→近侍编制、原文未言佩章（留白）；20 级→圣棺、不屑配章（不下移）。'
 '「圣骑士阶段」为原文用语、非第六阶；16 级＝中枢／宫廷骑士之级，与岗位两条线不互推；拉法叶是否圣棺原文未明、不补。'
 '不改 §3.2 拉法叶条、不改 V3.2 块正文，只在 §5.3 加括注、V3.2 防误判①补交叉。'
 'md **25,767 行／4,145,211 B／裸 LF 0**；docx **2,435,048 B**；四件套全绿（缺空行 1、表格异常 2 块、连续空行 0）；'
 '归档实数 **287／426／201／19，942 件／948 MB**；未上传资料库。 |')
lines[k]=lines[k].replace('| **当前版本** |','| **上一版** |',1)
lines=lines[:k]+[new]+lines[k:]
d='\r\n'.join(lines)
open(p,'wb').write(d.encode('utf-8'))
b=open(p,'rb').read()
assert b.count(b'\n')==b.count(b'\r\n')
print('台账 ok',len(b))

# ---------- 索引 ----------
p2='历史版本/00_归档索引.md'
raw2=open(p2,'rb').read().decode('utf-8').replace('\r\n','\n')
L=raw2.split('\n')
for j,l in enumerate(L):
    if l.startswith('| `设定集各版\\`'):
        L[j]=re.sub(r'\| \d+ \|$','| 287 |',l)
    elif l.startswith('| `脚本各版\\`'):
        L[j]=re.sub(r'\| \d+ \|$','| 426 |',l)
entry=('**V4.8 骑士身份更正**（2026-11-27 · 用户令）：**皇家2号骑士（16 级·圣骑士阶段·皇帝近侍编制）≠ 帝国第二骑士拉法叶'
 '（序位榜第 2·所罗门钥匙圣铠）**，两人不并。原文五条：后传 L343／L143／L1711、前传 L333／L2371。'
 '立**三层刻度**（10–13 阶巴思勋章／16 级近侍未言佩章／20 级圣棺不屑配章）；「圣骑士阶段」为原文用语、非第六阶；'
 '不改 §3.2 拉法叶条与 V3.2 块正文。归档：V4.7 md／docx 2 件＋脚本 2 件，根目录只留 V4.8；'
 '实数 **287／426／201／19，合计 942 件／948 MB**。')
j=[x for x,l in enumerate(L) if l.startswith('**V4.7 卷二第101–102章')]
assert len(j)==1,(len(j))
L=L[:j[0]]+[entry,'']+L[j[0]:]
d2='\r\n'.join(L)
open(p2,'wb').write(d2.encode('utf-8'))
b2=open(p2,'rb').read()
assert b2.count(b'\n')==b2.count(b'\r\n'),'索引裸LF'
print('索引 ok',len(b2))
